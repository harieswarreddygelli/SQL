-- DELETE COMMAND IS USED TO DELETE A DATA PRESENT IN A TABLE
-- THERE ARE DIFFERENT SCENARIOS

-- 1. DELETE SPECIFIC RECORD
DELETE FROM STUDENT WHERE NAME='RAM';
COMMIT;-- Saves the deletion permanently

-- 2. DELETE MULTIPLE RECORDS BASED ON A CONDITION
DELETE FROM STUDENT WHERE AGE >20;
COMMIT;-- Saves the deletion permanently

-- 3. DELETE FULL DATA AVAILABLE IN THE TABLE
DELETE FROM STUDENT ;
ROLLBACK; -- USED TO RETRIVE DATA ONLY WHEN COMMIT IS NOT USED